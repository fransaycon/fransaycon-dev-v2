// Build-time generator for LQIP (Low-Quality Image Placeholder) blur-up previews.
//
// Reads every image in src/project-files/, produces a tiny (~24px wide) blurred
// WebP encoded as a base64 data URI, and writes them to a generated TypeScript
// map keyed by the file's basename. These data URIs are embedded in the bundle
// and render instantly (no network request) while the full image downloads.
//
// Run with: pnpm generate-lqip

import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, extname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const __dirname = dirname(fileURLToPath(import.meta.url));
const SOURCE_DIR = resolve(__dirname, "../src/project-files");
const OUTPUT_FILE = resolve(__dirname, "../src/data/lqip.generated.ts");
const SUPPORTED = new Set([".webp", ".png", ".jpg", ".jpeg", ".avif"]);
const PLACEHOLDER_WIDTH = 24;

async function main() {
	const files = (await readdir(SOURCE_DIR))
		.filter((file) => SUPPORTED.has(extname(file).toLowerCase()))
		.sort();

	const entries = {};
	for (const file of files) {
		const basename = file.slice(0, file.length - extname(file).length);
		const buffer = await readFile(join(SOURCE_DIR, file));
		const placeholder = await sharp(buffer)
			.resize(PLACEHOLDER_WIDTH, null, { fit: "inside" })
			.webp({ quality: 40 })
			.toBuffer();
		entries[basename] =
			`data:image/webp;base64,${placeholder.toString("base64")}`;
	}

	const body = Object.entries(entries)
		.map(([key, value]) => `\t"${key}": "${value}",`)
		.join("\n");

	const contents = `// AUTO-GENERATED by scripts/generate-lqip.mjs. Do not edit by hand.
// Run \`pnpm generate-lqip\` to regenerate after adding or changing project images.

/** Base64 blur-up placeholders keyed by project-file basename. */
export const lqip: Record<string, string> = {
${body}
};
`;

	await writeFile(OUTPUT_FILE, contents, "utf8");
	console.log(
		`Generated ${Object.keys(entries).length} LQIP placeholders -> ${OUTPUT_FILE}`,
	);
}

main().catch((error) => {
	console.error(error);
	process.exit(1);
});
